"""Keep Vercel static HTML CSP hashes in sync with the standalone source.

Run with --write after editing queue3d.html or offline.html; --check is run by QC.
Only the dedicated security header rule is updated; other Vercel settings are preserved.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from server.security import content_policy, script_hashes, standard_headers  # noqa: E402

SOURCES = ("/static/(.*)", "/offline.html")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    file = ROOT / "vercel.json"
    config = json.loads(file.read_text(encoding="utf-8"))
    hashes = script_hashes()
    constants = (
        '"""Generated by scripts/security-headers.py; do not edit by hand."""\n\n'
        "STATIC_SCRIPT_HASHES = (\n"
        + "".join("    " + json.dumps(value) + ",\n" for value in hashes)
        + ")\n"
    )
    constants_file = ROOT / "server/csp_hashes.py"
    headers = {
        **standard_headers(),
        "Strict-Transport-Security": "max-age=31536000",
        "Content-Security-Policy": content_policy(hashes),
    }
    rules = [
        {"source": source, "headers": [{"key": k, "value": v} for k, v in headers.items()]}
        for source in SOURCES
    ]
    current = [r for r in config.get("headers", []) if r["source"] in SOURCES]
    if args.write:
        config["headers"] = [
            r
            for r in config.get("headers", [])
            if r["source"] not in (*SOURCES, "/(static/(.*)|offline.html)")
        ]
        config["headers"].extend(rules)
        file.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8", newline="\n")
        constants_file.write_text(constants, encoding="utf-8", newline="\n")
    elif current != rules or constants_file.read_text(encoding="utf-8") != constants:
        raise SystemExit(
            "Static security headers are stale: python scripts/security-headers.py --write"
        )
    print("Static security headers and inline script hashes match.")


if __name__ == "__main__":
    main()
